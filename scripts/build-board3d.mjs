// Bundles the 3D board (three.js + src/board3d/scene) into one HTML page that
// the app loads into a WebView, so it works offline. Run after changing the scene:
//   npm run build:board3d
// Pass --preview <file> to also write a page that can be opened in a browser.
import {build} from 'esbuild';
import {writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

const result = await build({
  entryPoints: [`${root}src/board3d/scene/main.ts`],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'chrome80',
  write: false,
  legalComments: 'none',
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const page = (extra = '') => `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>
html, body { margin: 0; height: 100%; overflow: hidden; background: transparent;
  -webkit-user-select: none; user-select: none; -webkit-touch-callout: none;
  -webkit-tap-highlight-color: transparent; touch-action: none; }
canvas { display: block; width: 100vw; height: 100vh; }
</style>
</head>
<body>
${extra}<script>${script}</script>
</body>
</html>`;

const html = page();
writeFileSync(
  `${root}src/board3d/boardHtml.generated.ts`,
  '// Generated by scripts/build-board3d.mjs. Do not edit; run `npm run build:board3d`.\n' +

    `export default ${JSON.stringify(html)};\n`,
);
console.log(`board3d: ${(html.length / 1024).toFixed(0)} KB`);

const previewIndex = process.argv.indexOf('--preview');
if (previewIndex !== -1) {
  const harness = `<script>
window.ReactNativeWebView = {postMessage: m => console.log('to app:', m)};
</script>`;
  writeFileSync(process.argv[previewIndex + 1], page(harness));
}
